// Content helper for writing posts and docs.
//
//   dart run tool/content.dart new-post "My post title" [--tags "Unreal, Devlog"] [--folder]
//   dart run tool/content.dart new-doc <Plugin-Folder> "Page title"
//   dart run tool/content.dart sync     # register content folders in pubspec.yaml
//   dart run tool/content.dart check    # find broken images and bad front matter
//
// Flutter only bundles folders listed in pubspec.yaml, so `new-post` and
// `new-doc` run `sync` for you. Run it yourself after adding folders by hand.
import 'dart:io';

import 'package:yaml/yaml.dart';

const _begin = '    # >>> content (generated by `dart run tool/content.dart sync`, do not edit)';
const _end = '    # <<< content';

void main(List<String> args) {
  if (args.isEmpty) return _usage();
  switch (args.first) {
    case 'sync':
      _sync();
    case 'new-post':
      _newPost(args.skip(1).toList());
    case 'new-doc':
      _newDoc(args.skip(1).toList());
    case 'check':
      exitCode = _check() ? 0 : 1;
    default:
      _usage();
  }
}

void _usage() {
  stdout.writeln('''
Usage:
  dart run tool/content.dart new-post "Title" [--tags "A, B"] [--folder]
  dart run tool/content.dart new-doc <Folder> "Title"
  dart run tool/content.dart sync
  dart run tool/content.dart check''');
}

String _slug(String s) => s
    .toLowerCase()
    .replaceAll(RegExp(r"['’]"), '')
    .replaceAll(RegExp(r'[^a-z0-9]+'), '-')
    .replaceAll(RegExp(r'^-+|-+$'), '');

String _today() => DateTime.now().toIso8601String().substring(0, 10);

/// Rewrites the generated asset block in pubspec.yaml with every folder under content/.
void _sync() {
  final dirs = <String>['content/'];
  for (final entity in Directory('content').listSync(recursive: true)) {
    if (entity is! Directory) continue;
    final path = entity.path.replaceAll(r'\', '/');
    if (path.split('/').any((part) => part.startsWith('.'))) continue;
    if (path.contains(' ')) stderr.writeln('warning: "$path" contains spaces; use dashes instead.');
    dirs.add('$path/');
  }
  dirs.sort();

  final pubspec = File('pubspec.yaml');
  final text = pubspec.readAsStringSync();
  final block = [_begin, for (final d in dirs) '    - $d', _end].join('\n');
  final start = text.indexOf(_begin);
  final end = text.indexOf(_end);
  if (start < 0 || end < 0) {
    stderr.writeln('Could not find the content markers in pubspec.yaml.');
    exitCode = 1;
    return;
  }
  final updated = text.replaceRange(start, end + _end.length, block);
  if (updated != text) pubspec.writeAsStringSync(updated);
  stdout.writeln('Registered ${dirs.length} content folders in pubspec.yaml.');
}

void _newPost(List<String> args) {
  final folder = args.remove('--folder');
  String? tags;
  final tagIndex = args.indexOf('--tags');
  if (tagIndex >= 0 && tagIndex + 1 < args.length) {
    tags = args[tagIndex + 1];
    args.removeRange(tagIndex, tagIndex + 2);
  }
  if (args.isEmpty) return _usage();
  final title = args.join(' ');
  final name = '${_today()}-${_slug(title)}';
  final file = folder ? File('content/blog/$name/index.md') : File('content/blog/$name.md');
  if (file.existsSync()) {
    stderr.writeln('${file.path} already exists.');
    exitCode = 1;
    return;
  }
  final tagList = (tags ?? '').split(',').map((t) => t.trim()).where((t) => t.isNotEmpty).join(', ');
  file
    ..createSync(recursive: true)
    ..writeAsStringSync('''
---
title: ${_yamlString(title)}
authors: [denizhan]
tags: [$tagList]
description: One or two sentences shown on the post card.
# image: cover.jpg   # optional cover, relative to this file
draft: true          # visible only while running locally; delete this line to publish
---

The first paragraph is the hook.

<!-- truncate -->

## First section

Write here. Images go next to the file: ![Alt text](./my-image.png)
''');
  stdout.writeln('Created ${file.path}');
  _sync();
}

void _newDoc(List<String> args) {
  if (args.length < 2) return _usage();
  final folderName = args.first;
  final title = args.skip(1).join(' ');
  final dir = Directory('content/docs/$folderName');
  final isNewFolder = !dir.existsSync();
  dir.createSync(recursive: true);

  if (isNewFolder) {
    File('${dir.path}/_category_.yaml').writeAsStringSync('''
label: ${_yamlString(folderName.replaceAll('-', ' '))}
summary: One sentence about this plugin, shown on cards.
# description: Longer text for the plugin's overview page.
# thumbnail: thumbnail.png   # square image in this folder
# featured: true             # show in the home page spotlight
# links:
#   fab: https://www.fab.com/listings/...
#   github: https://github.com/...
''');
    stdout.writeln('Created ${dir.path}/_category_.yaml');
  }

  final existing = dir.listSync().whereType<File>().where((f) => f.path.endsWith('.md')).length;
  final words = title.split(RegExp(r'\s+')).where((w) => w.isNotEmpty);
  final fileName = words.map((w) => w[0].toUpperCase() + w.substring(1)).join('-');
  final file = File('${dir.path}/$fileName.md');
  if (file.existsSync()) {
    stderr.writeln('${file.path} already exists.');
    exitCode = 1;
    return;
  }
  file.writeAsStringSync('''
---
sidebar_position: ${existing + 1}
---

# $title

${existing == 0 ? '::plugin-links\n\n' : ''}Introduce the page in a sentence or two.

## Section

:::tip
Admonitions: note, tip, info, warning, danger.
:::
''');
  stdout.writeln('Created ${file.path}');
  _sync();
}

/// Reports images that don't exist and front matter that doesn't parse.
bool _check() {
  var problems = 0;
  final files = Directory('content')
      .listSync(recursive: true)
      .whereType<File>()
      .map((f) => f.path.replaceAll(r'\', '/'))
      .where((p) => p.endsWith('.md') || p.contains('_category_.'));

  for (final path in files) {
    final text = File(path).readAsStringSync();
    final dir = path.substring(0, path.lastIndexOf('/'));

    String? yamlSource = path.endsWith('.md')
        ? RegExp(r'^---\s*\n([\s\S]*?)\n---').firstMatch(text)?.group(1)
        : text;
    try {
      if (yamlSource != null && yamlSource.trim().isNotEmpty) loadYaml(yamlSource);
    } catch (e) {
      stdout.writeln('$path: front matter is not valid YAML ($e)');
      problems++;
    }

    final refs = <String>[
      for (final m in RegExp(r'!\[[^\]]*\]\(([^)\s]+)').allMatches(text)) m.group(1)!,
      for (final m in RegExp(r'^(?:image|thumbnail):\s*(\S+)', multiLine: true).allMatches(text)) m.group(1)!,
    ];
    for (final ref in refs) {
      if (ref.startsWith('http://') || ref.startsWith('https://')) continue;
      final resolved = ref.startsWith('/assets/')
          ? ref.substring(1)
          : ref.startsWith('/')
              ? 'content$ref'
              : Uri(path: '$dir/').resolve(ref).path;
      if (!File(Uri.decodeFull(resolved)).existsSync()) {
        stdout.writeln('$path: missing image "$ref"');
        problems++;
      }
    }
  }
  stdout.writeln(problems == 0 ? 'All good.' : '$problems problem(s) found.');
  return problems == 0;
}

String _yamlString(String s) => '"${s.replaceAll('"', r'\"')}"';
